export type Labels = typeof mr;
export const labelsFor = (lang: Lang): Labels => (lang === "en" ? en : mr);

// The language and digit cookies' values. The book is Marathi unless English was chosen, and
// digits follow the language until they are chosen on their own.
export const readLang = (value: string | undefined): Lang => (value === "en" ? "en" : "mr");
export const readDigits = (value: string | undefined, lang: Lang): Digits =>
  value === "deva" || value === "latn" ? value : lang === "mr" ? "deva" : "latn";

export const headName = (head: Head, lang: Lang) => (lang === "en" ? head.nameEn : head.nameMr);
export const fieldLabel = (field: ExtraField, lang: Lang) => (lang === "en" ? field.labelEn : field.labelMr);

const DEVANAGARI = "०१२३४५६७८९";
export const toDigits = (text: string, digits: Digits) =>
  digits === "deva" ? text.replace(/\d/g, (d) => DEVANAGARI[Number(d)]) : text;

// Rupees as the book writes them: Indian grouping, paise only when there are any.
export function money(n: number, digits: Digits) {
  const whole = Number.isInteger(n);
  const text = Math.abs(n).toLocaleString("en-IN", { minimumFractionDigits: whole ? 0 : 2, maximumFractionDigits: 2 });
  return toDigits(`${n < 0 ? "−" : ""}${text}`, digits);
}

export const weightText = (n: number, lang: Lang, digits: Digits) => `${toDigits(n.toFixed(3), digits)} ${labelsFor(lang).gram}`;

// A shop calendar day (YYYY-MM-DD) written out in full.
export function longDate(day: string, lang: Lang, digits: Digits) {
  const [year, month, date] = day.split("-").map(Number);
  const t = labelsFor(lang);
  const weekday = t.weekdays[new Date(Date.UTC(year, month - 1, date)).getUTCDay()];
  return toDigits(`${weekday}, ${date} ${t.months[month - 1]} ${year}`, digits);
}

export const shiftDay = (day: string, by: number) => {
  const [year, month, date] = day.split("-").map(Number);
  return new Date(Date.UTC(year, month - 1, date + by)).toISOString().slice(0, 10);
};
